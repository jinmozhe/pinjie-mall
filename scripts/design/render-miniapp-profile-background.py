"""Generate the fixed profile SVG; optionally render Pillow asset previews.

SVG generation uses only the standard library. Pillow is needed only for previews.
Outputs must be new files, so existing artwork cannot be overwritten accidentally.
"""

import argparse
import math
import random
from pathlib import Path
from xml.sax.saxutils import escape

WIDTH, HEIGHT, SEED = 1440, 4480, 20261117
FADE_START, FADE_END = 2000, 4200
STOPS = [(0, "#c92320"), (300, "#d42c26"), (550, "#f45b4d"),
         (820, "#ff9a88"), (1100, "#fbdcd0"), (1450, "#fff4ec"),
         (2200, "#fcf2eb"), (3200, "#fff5ef"), (4480, "#ffffff")]
LINES = [([(45, 400), (245, 140), (815, 420), (1160, 50)], "#ffe2c8", 0.32),
         ([(1040, 2600), (1360, 2420), (1455, 2655)], "#c58b72", 0.25)]
SCREENS = [(320, 568), (375, 667), (390, 844), (430, 932),
           (360, 800), (412, 915), (390, 1180), (390, 1400)]


def geometry():
    rng = random.Random(SEED)
    xs = [0, 350, 720, 1090, WIDTH]
    # Keep the approved upper pattern unchanged and extend its lower edge.
    ys = [0, 260, 560, 900, 1300, 1760, 2240, 2700, 3200]
    grid = [[(x if col in (0, 4) else x + rng.randint(-110, 110),
              y if row in (0, len(ys) - 1) else y + rng.randint(-65, 65))
             for col, x in enumerate(xs)] for row, y in enumerate(ys)]
    triangles = []
    for row in range(len(ys) - 1):
        for col in range(len(xs) - 1):
            a, b = grid[row][col:col + 2]
            d, c = grid[row + 1][col:col + 2]
            pairs = [(a, b, c), (a, c, d)] if rng.random() < 0.5 else [(a, b, d), (b, c, d)]
            for points in pairs:
                upper = sum(y for _, y in points) / 3 < 1000
                light = rng.random() < 0.5
                color = ("#ffb69c" if light else "#851710") if upper else ("#ffffff" if light else "#c6afa2")
                opacity = round(rng.uniform(0.04, 0.13) if upper else rng.uniform(0.06, 0.17), 3)
                triangles.append((points, color, opacity))
    for y0, y1 in [(3200, 3800), (3800, HEIGHT)]:
        for x0, x1 in zip(xs, xs[1:]):
            points = [(x0, y0), (x1, y0), (x1, y1)]
            triangles.append((points, "#c6afa2", round(rng.uniform(0.06, 0.12), 3)))
            triangles.append(([(x0, y0), (x1, y1), (x0, y1)], "#ffffff", 0.1))
    return triangles


def svg(triangles):
    lines = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}" preserveAspectRatio="xMidYMin meet">',
             f'  <desc>{escape(f"Fixed low-poly profile background, seed {SEED}. Generated by render-miniapp-profile-background.py.")}</desc>',
             f'  <defs><linearGradient id="base" gradientUnits="userSpaceOnUse" x1="0" y1="0" x2="0" y2="{HEIGHT}">']
    lines += [f'    <stop offset="{y / HEIGHT:.6f}" stop-color="{color}"/>' for y, color in STOPS]
    lines += ['  </linearGradient>',
              f'  <linearGradient id="fade" gradientUnits="userSpaceOnUse" x1="0" y1="{FADE_START}" x2="0" y2="{FADE_END}">',
              '    <stop offset="0" stop-color="#ffffff" stop-opacity="0"/>',
              '    <stop offset="1" stop-color="#ffffff" stop-opacity="1"/>',
              '  </linearGradient></defs>', f'  <path fill="url(#base)" d="M0 0h{WIDTH}v{HEIGHT}H0z"/>']
    for points, color, opacity in triangles:
        path = "M" + "L".join(f"{x} {y}" for x, y in points) + "z"
        lines.append(f'  <path fill="{color}" fill-opacity="{opacity}" d="{path}"/>')
    for points, color, opacity in LINES:
        path = "M" + "L".join(f"{x} {y}" for x, y in points)
        lines.append(f'  <path fill="none" stroke="{color}" stroke-opacity="{opacity}" stroke-width="1.5" d="{path}"/>')
    lines += ['  <path fill="none" stroke="#c58b72" stroke-opacity="0.23" stroke-width="1.5" d="M18 2080C270 2130 270 2510-30 2570"/>',
              f'  <path fill="url(#fade)" d="M0 0h{WIDTH}v{HEIGHT}H0z"/>', '</svg>']
    return "\n".join(lines) + "\n"


def rgb(color):
    return tuple(int(color[i:i + 2], 16) for i in (1, 3, 5))


def render_previews(directory, triangles):
    from PIL import Image, ImageDraw, ImageFont

    directory.mkdir(parents=True, exist_ok=True)
    image = Image.new("RGB", (WIDTH, HEIGHT))
    draw = ImageDraw.Draw(image)
    for y in range(HEIGHT):
        for (y0, c0), (y1, c1) in zip(STOPS, STOPS[1:]):
            if y0 <= y <= y1:
                factor = (y - y0) / (y1 - y0)
                color = tuple(round(a + (b - a) * factor) for a, b in zip(rgb(c0), rgb(c1)))
                draw.line((0, y, WIDTH, y), fill=color)
                break
    overlay = ImageDraw.Draw(image, "RGBA")
    for points, color, opacity in triangles:
        overlay.polygon(points, fill=(*rgb(color), round(opacity * 255)))
    for points, color, opacity in LINES:
        overlay.line(points, fill=(*rgb(color), round(opacity * 255)), width=2)
    curve = []
    for step in range(101):
        t = step / 100
        curve.append(tuple(round((1-t)**3*a + 3*(1-t)**2*t*b + 3*(1-t)*t*t*c + t**3*d)
                           for a, b, c, d in zip((18, 2080), (270, 2130), (270, 2510), (-30, 2570))))
    overlay.line(curve, fill=(*rgb("#c58b72"), 59), width=2)
    for y in range(FADE_START, HEIGHT):
        alpha = round(min(1, (y - FADE_START) / (FADE_END - FADE_START)) * 255)
        overlay.line((0, y, WIDTH, y), fill=(255, 255, 255, alpha))
    with (directory / "profile-background-preview.png").open("xb") as target:
        image.save(target, format="PNG", optimize=True)

    sheet = Image.new("RGB", (1200, 1440), "#e8e7e4")
    sheet_draw = ImageDraw.Draw(sheet)
    font = ImageFont.load_default(size=20)
    for index, (width, height) in enumerate(SCREENS):
        scale = max(width / WIDTH, height / HEIGHT)
        rendered_width, rendered_height = math.ceil(WIDTH * scale), math.ceil(HEIGHT * scale)
        assert rendered_width >= width and rendered_height >= height
        resized = image.resize((rendered_width, rendered_height), Image.Resampling.LANCZOS)
        left = (rendered_width - width) // 2
        crop = resized.crop((left, 0, left + width, height))
        crop.thumbnail((264, 640), Image.Resampling.LANCZOS)
        x, y = index % 4 * 300 + 18, index // 4 * 720 + 54
        sheet.paste(crop, (x, y))
        sheet_draw.text((x, y - 32), f"{width} x {height}", fill="#343434", font=font)
    with (directory / "profile-background-viewport-previews.png").open("xb") as target:
        sheet.save(target, format="PNG", optimize=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--svg-out", type=Path, required=True, help="New SVG output path")
    parser.add_argument("--preview-dir", type=Path, help="Optional new PNG previews; requires Pillow")
    args = parser.parse_args()
    triangles = geometry()
    with args.svg_out.open("x", encoding="utf-8", newline="\n") as target:
        target.write(svg(triangles))
    if args.preview_dir:
        render_previews(args.preview_dir, triangles)
    print(f"PROFILE_BACKGROUND_OK {WIDTH}x{HEIGHT} seed={SEED} triangles={len(triangles)} bytes={args.svg_out.stat().st_size}")


if __name__ == "__main__":
    main()
